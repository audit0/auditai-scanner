describe("ALTER TABLE, DROP TABLE and file order", () => {
  it("applies column changes in order", () => {
    const { tables } = parse(
      `create table public.t (id uuid primary key, a text, b text not null, c int default 1, d varchar(10));`,
      `alter table public.t add column if not exists e uuid references public.t (id);
       alter table t add f text not null default '', drop column a;
       alter table only "public"."t" alter column b drop not null, alter column c drop default;
       alter table t alter c set not null, alter column d set data type text;
       alter table t alter column e type uuid using e::uuid, alter column b set default 'x';
       alter table t rename column d to description;
       alter table if exists t add column if not exists f text;`,
    );
    const t = tables.get("t");
    expect(t?.columns).toEqual(["id", "b", "c", "description", "e", "f"]);
    const c = cols(tables, "t");
    expect([c.b?.nullable, c.b?.hasDefault]).toEqual([true, true]);
    expect([c.c?.nullable, c.c?.hasDefault]).toEqual([false, false]);
    expect(c.description?.type).toBe("text");
    expect(c.e?.references).toEqual({ table: "t", column: "id" });
    expect([c.f?.nullable, c.f?.hasDefault, c.f?.type]).toEqual([false, true, "text"]);
  });

  it("follows renames and drops into foreign keys", () => {
    const { tables } = parse(
      `create table tenants (id uuid primary key, code text unique);
       create table invoices (id uuid primary key, tenant_id uuid references tenants (id), tenant_code text);
       alter table invoices add constraint inv_code_fk foreign key (tenant_code) references tenants (code);`,
      `alter table tenants rename column id to tenant_uuid;
       alter table tenants rename to organizations;`,
    );
    expect([...tables.keys()]).toEqual(["invoices", "organizations"]);
    expect(cols(tables, "invoices").tenant_id?.references).toEqual({
      table: "organizations",
      column: "tenant_uuid",
    });
    const dropped = parse(
      `create table tenants (id uuid primary key, code text);
       create table invoices (id uuid, tenant_id uuid references tenants (id), tenant_code text,
         constraint inv_code_fk foreign key (tenant_code) references tenants (code));
       alter table invoices drop constraint if exists inv_code_fk;
       alter table tenants drop column id cascade;`,
    );
    expect(cols(dropped.tables, "invoices").tenant_id?.references).toBeNull();
    expect(cols(dropped.tables, "invoices").tenant_code?.references).toBeNull();
    const gone = parse(
      "create table a (id int primary key); create table b (a_id int references a); drop table if exists a cascade;",
    );
    expect([...gone.tables.keys()]).toEqual(["b"]);
    expect(cols(gone.tables, "b").a_id?.references).toBeNull();
  });

  it("drops a default-named inline foreign key and reads PRIMARY KEY USING INDEX", () => {
    const { tables } = parse(`
      create table "public"."todos" ("id" bigint not null, "user_id" uuid references auth.users);
      CREATE UNIQUE INDEX todos_pkey ON public.todos USING btree (id);
      alter table "public"."todos" add constraint "todos_pkey" PRIMARY KEY using index "todos_pkey";
      alter table "public"."todos" drop constraint "todos_user_id_fkey";`);
    expect(cols(tables, "todos").user_id?.references).toBeNull();
    expect(cols(tables, "todos").id?.nullable).toBe(false);
  });

  it("ignores column changes for tables the migrations never create", () => {
    const { tables } = parse(
      "alter table ghost add column x int; alter table ghost2 enable row level security;",
    );
    expect([...tables.keys()]).toEqual(["ghost2"]);
    expect(tables.get("ghost2")?.columnInfo).toEqual([]);
  });
});

