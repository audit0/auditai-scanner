function parse(...files: string[]) {
  const tables = new Map<string, RlsTable>();
  files.forEach((sql, i) => {
    parseSqlForRls(`m${i}.sql`, sql, tables);
  });
  return { tables, ...sqlSchemaFor(tables) };
}

function cols(tables: Map<string, RlsTable>, table: string): Record<string, ColumnInfo> {
  return Object.fromEntries((tables.get(table)?.columnInfo ?? []).map((c) => [c.name, c]));
}

