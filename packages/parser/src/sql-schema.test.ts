function tempProject(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), "auditai-sql-"));
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  }
  return dir;
}

describe("splitSqlStatements", () => {
  it("does not split inside strings, quoted identifiers, dollar bodies or comments", () => {
    const sql = [
      "insert into t (a) values ('x;y'); -- c;omment",
      'create table "we;ird" (id int);',
      "/* block; /* nested; */ still */ select E'it\\'s;';",
      "create function f() returns int as $function$ select 1; $$ not the end $$; $function$ language sql;",
      "select 2",
    ].join("\n");
    const stmts = splitSqlStatements(sql);
    expect(stmts.map((s) => s.tokens[0]?.value)).toEqual([
      "insert",
      "create",
      "select",
      "create",
      "select",
    ]);
    expect(stmts.map((s) => s.line)).toEqual([1, 2, 3, 4, 5]);
    expect(stmts[2]?.tokens[1]?.value).toBe("it's;");
    expect(stmts[3]?.tokens.find((t) => t.kind === "string")?.value).toBe(
      " select 1; $$ not the end $$; ",
    );
  });

  it("survives unterminated strings, bodies and comments", () => {
    for (const bad of ["select 'abc", 'select "abc', "select $$ abc", "select /* abc", "$", "'"]) {
      expect(() => splitSqlStatements(bad)).not.toThrow();
    }
  });
});

